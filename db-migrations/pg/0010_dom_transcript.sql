-- Rendered text for threads whose text never arrives any other way.
--
-- The encrypted store delivers envelopes: `upsertMessage` carries the null sentinel
-- `[9]` where text would be, measured at 0 of 72,670 rows. The plaintext is not on
-- disk either -- a forensic read of the browser profile's IndexedDB found no record
-- anywhere mentioning a `mid.`, for either sync group -- so it exists only in the
-- renderer while the client is running. The page's bootstrap payloads do carry text,
-- but only for the regular inbox, which is already archived.
--
-- What the renderer shows and what the archive can key are therefore disjoint: the
-- rendered conversation has no message id on it anywhere (not in an attribute, not in
-- React's own props -- 0 of 401 elements), and the rendered timestamps are relative
-- ("3 dni temu"), so there is nothing exact to match on either.
--
-- These tables exist because the alternative was worse. Aligning rendered text onto
-- `message` rows by order would be guessing, and this project has a rule about that:
-- pattern-matching has produced a wrong answer every single time it has been tried.
-- A wrong answer here means one person's sentence filed under another person's
-- message, silently, in a private archive. So rendered text is stored as its own
-- record and is NEVER joined to `message`. A capture is an immutable, contiguous
-- excerpt of a conversation as it appeared at one moment, and that is all it claims.
--
-- Unlike every other write in this project, producing these rows is not free: the
-- harvester must open the conversation, which issues `LSMarkThreadRead` and marks it
-- read on every device the account owns. See CLAUDE.md.

CREATE TABLE IF NOT EXISTS dom_capture (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    text NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    thread_key    text NOT NULL,
    captured_at   timestamptz NOT NULL DEFAULT now(),
    -- Hash of the whole run. A thread that has not changed renders identically, and
    -- storing that again would grow the table without adding a word.
    run_hash      text NOT NULL,
    message_count integer NOT NULL,
    FOREIGN KEY (account_id, thread_key)
        REFERENCES thread (account_id, thread_key) ON DELETE CASCADE,
    UNIQUE (account_id, thread_key, run_hash)
);

CREATE INDEX IF NOT EXISTS dom_capture_thread_idx
    ON dom_capture (account_id, thread_key, captured_at DESC);

CREATE TABLE IF NOT EXISTS dom_message (
    capture_id    bigint NOT NULL REFERENCES dom_capture (id) ON DELETE CASCADE,
    -- Oldest first, as rendered. Position within THIS capture only: it is not a
    -- position in the conversation and must not be treated as one, because a later
    -- capture scrolled further back will number the same message differently.
    ordinal       integer NOT NULL,
    -- From rendered alignment, which is how the client distinguishes the account
    -- holder in a one-to-one thread. NULL when it could not be determined; it is a
    -- rendering fact, not an identity, so there is deliberately no participant FK.
    outgoing      boolean,
    sender_name   text,
    text          text NOT NULL,
    -- The leading part of the client's own accessibility label, verbatim. Measured
    -- against a live capture it looks like:
    --
    --     Wprowadz, Wiadomosc wyslana niedziela 19:58
    --     \__ UI hint __/\__ "message sent" __/\_ weekday _/\_ clock _/
    --
    -- 15 of 15 labels carried a clock, which is why this is stored and the visible
    -- bubble's "3 dni temu" is not. But note what is NOT here: there is no calendar
    -- date, only a weekday, so a label resolves to an instant for about a week and
    -- then becomes ambiguous. It is kept because a weekday and a time beat nothing,
    -- not because it is a timestamp.
    --
    -- Verbatim and not parsed, including the locale boilerplate. Parsing would mean
    -- owning weekday names per locale, and the result still would not be an instant.
    time_label text,
    -- Whatever stands between the clock and the colon, as rendered. Includes the
    -- client's own boilerplate, so it is a label and not a name -- and deliberately
    -- not a participant id, because nothing here resolves to one.
    sender_label text,
    search        tsvector GENERATED ALWAYS AS (to_tsvector('simple', text)) STORED,
    PRIMARY KEY (capture_id, ordinal)
);

CREATE INDEX IF NOT EXISTS dom_message_search_idx ON dom_message USING gin (search);
